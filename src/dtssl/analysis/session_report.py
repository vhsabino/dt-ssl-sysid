"""Sanity report of a recorded twin session (``dtssl serve --record DIR``) in the log contract.

For a session directory with ``commands.parquet`` + ``processed_robots.parquet`` (written by
``dtssl.bridge.recorder.SessionRecorder``): contract check (columns of the extracted competition
logs), robots/duration/ticks, command statistics per robot and pooled (|v|, |w| quantiles, fraction
of samples with |w| below the body-equivalent deadzone 0.58 rad/s, kick/chip/dribbler flags), the
same statistics for a competition label of the dataset for comparison (default ``shoot_to_goal``),
and the harness consistency check: each robot is loaded with ``dtssl.data.loader.load_event`` and
replayed through the paper harness (re-anchored windows, official theta) with the analytic twin and
the ideal kinematics. When the session was generated by the ``fopdt`` backend the twin must reproduce
the recorded poses to the mm (recorder -> parquet -> loader -> harness round trip); the ideal
kinematics gives the usual ~0.1 m gap.

    dtssl analysis run session_report --kw session=results/sessao_01 [label=shoot_to_goal] [robots=1,5]

Output: ``results/session_report_<name>_<stamp>.md`` (+ ``.json``).
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from dtssl.analysis import common as C
from dtssl.eval.metrics import _window_errors
from dtssl.models import AnalyticFOPDTPlant, IdealKinematicPlant
from dtssl.sim.rollout import rollout_segment

NAME = "session_report"
KIND = "report"
CLAIM = "Recorded twin session: log-contract check, command statistics vs competition, harness round trip"
REQUIRES = ()
CMD_COLS = ["timestamp", "timestamp_event", "robot_id", "move_x", "move_y", "move_w", "actuation_kick_strength",
            "actuation_front", "actuation_chip", "actuation_charge", "actuation_dribbler",
            "actuation_dribbler_velocity"]
ROB_COLS = ["timestamp", "timestamp_event", "team", "robot_id", "position_x", "position_y", "position_w",
            "velocity_x", "velocity_y", "velocity_norm"]
W_DEADZONE_BODY = 0.58     # rad/s, body-equivalent of the 1.567 rad/s wheel deadzone for pure rotation


def cmd_stats(c: pd.DataFrame) -> dict:
    v = np.hypot(c["move_x"].to_numpy(float), c["move_y"].to_numpy(float))
    w = np.abs(c["move_w"].to_numpy(float))
    return dict(n=int(len(c)), v_med=float(np.median(v)), v_p90=float(np.percentile(v, 90)), v_max=float(v.max()),
                w_med=float(np.median(w)), w_p90=float(np.percentile(w, 90)), w_max=float(w.max()),
                w_below_dz=float((w < W_DEADZONE_BODY).mean()), v_above_2p9=float((v > 2.9).mean()),
                frac_idle=float(((v < 0.05) & (w < 0.1)).mean()))


def competition_stats(ctx: C.Ctx, label: str) -> dict | None:
    frames = []
    for ev in C.list_events(ctx.splits_dir, label):
        try:
            cmd, _ = C.read_event_csv(label, ev, dataset=ctx.dataset, data_root=ctx.data_root)
        except FileNotFoundError:
            continue
        frames.append(cmd[["move_x", "move_y", "move_w"]])
    if not frames:
        return None
    return dict(label=label, n_events=len(frames), **cmd_stats(pd.concat(frames, ignore_index=True)))


def compute(ctx: C.Ctx, session: str | Path, label: str = "shoot_to_goal", robots=None,
            stride: int | None = None) -> dict:
    from dtssl.data.loader import load_event
    from dtssl.sim.rollout import DEFAULT_STRIDE

    sdir = Path(session)
    if not sdir.is_absolute():
        sdir = ctx.root / sdir
    cp, rp = sdir / "commands.parquet", sdir / "processed_robots.parquet"
    c, r = pd.read_parquet(cp), pd.read_parquet(rp)
    contract = dict(commands_cols_ok=list(c.columns) == CMD_COLS, robots_cols_ok=list(r.columns) == ROB_COLS,
                    commands_extra=[x for x in c.columns if x not in CMD_COLS],
                    robots_extra=[x for x in r.columns if x not in ROB_COLS])
    ids = sorted(int(i) for i in c["robot_id"].unique())
    per_robot = {}
    for rid in ids:
        per_robot[rid] = cmd_stats(c[c["robot_id"] == rid])
    pooled = cmd_stats(c)
    flags = dict(kick_front_ticks=int(c["actuation_front"].sum()), chip_ticks=int(c["actuation_chip"].sum()),
                 dribbler_frac=float(c["actuation_dribbler"].mean()))
    extent = dict(x_m=(float(r["position_x"].min()) / 1000, float(r["position_x"].max()) / 1000),
                  y_m=(float(r["position_y"].min()) / 1000, float(r["position_y"].max()) / 1000))
    comp = competition_stats(ctx, label) if ctx.data_root.exists() else None
    # harness round trip
    P, H = ctx.params, ctx.horizons
    Hn = np.asarray(H, int)
    kref = H.index(int(ctx.mcfg["verdict"]["h_ref"]))
    stride = stride or DEFAULT_STRIDE
    sel = ids if not robots else [int(x) for x in robots]
    replay = {}
    for rid in sel:
        seg = load_event(cp, rp, robot_id=rid, meta={"event": f"{sdir.name}/robot{rid}", "label": sdir.name})
        rt = rollout_segment(seg, AnalyticFOPDTPlant(P), horizons=tuple(H), stride=stride)
        ri = rollout_segment(seg, IdealKinematicPlant(), horizons=tuple(H), stride=stride)
        Et = np.array([_window_errors(w, Hn)[0] for w in rt.windows])
        Ei = np.array([_window_errors(w, Hn)[0] for w in ri.windows])
        replay[rid] = dict(n=int(seg.n), duration_s=float(seg.duration_s), windows=int(rt.n_total), idle=int(rt.n_idle),
                           twin_med=[float(x) for x in np.median(Et, 0)], twin_p90=[float(x) for x in np.percentile(Et, 90, axis=0)],
                           ideal_med=[float(x) for x in np.median(Ei, 0)],
                           twin_med_href=float(np.median(Et[:, kref])), twin_p90_href=float(np.percentile(Et[:, kref], 90)),
                           ideal_med_href=float(np.median(Ei[:, kref])))
    return dict(session=str(sdir), name=sdir.name, contract=contract, robots=ids, ticks=int(c["timestamp_event"].nunique()),
                duration_s=float(c["timestamp_event"].max()), n_cmd_rows=int(len(c)), n_rob_rows=int(len(r)),
                teams=sorted(str(t) for t in r["team"].unique()), per_robot=per_robot, pooled=pooled, flags=flags,
                extent=extent, competition=comp, replay=replay, horizons=list(H), h_ref_s=float(H[kref] * ctx.ts))


def render(ctx: C.Ctx, R: dict) -> list[str]:
    L = C.result_header(f"Sessao gravada {R['name']}: contrato, estatisticas de comando e round trip no harness", ctx,
                        generator=f"dtssl.analysis.{NAME}", extra=f"sessao `{R['session']}`")
    ok = R["contract"]["commands_cols_ok"] and R["contract"]["robots_cols_ok"]
    L += [f"Contrato dos logs: {'OK' if ok else 'DIFERENTE'} (commands {len(CMD_COLS)} colunas, processed_robots {len(ROB_COLS)} colunas)"
          + ("" if ok else f" -- extras: {R['contract']['commands_extra']} / {R['contract']['robots_extra']}"),
          f"Robos {R['robots']} (team {R['teams']}), {R['ticks']} ticks = {R['duration_s']:.1f} s, "
          f"{R['n_cmd_rows']} linhas de comando, {R['n_rob_rows']} linhas de pose; posicoes x {R['extent']['x_m'][0]:.2f}..{R['extent']['x_m'][1]:.2f} m, "
          f"y {R['extent']['y_m'][0]:.2f}..{R['extent']['y_m'][1]:.2f} m.", "",
          "## Comandos (RMS por robo, m/s e rad/s)", "", "| robo | |v| med | |v| p90 | |w| med | |w| p90 | |w|<0.58 | parado |", "|---|---|---|---|---|---|---|"]
    for rid, s in R["per_robot"].items():
        L.append(f"| {rid} | {s['v_med']:.3f} | {s['v_p90']:.3f} | {s['w_med']:.3f} | {s['w_p90']:.3f} | {100*s['w_below_dz']:.1f} % | {100*s['frac_idle']:.1f} % |")
    p = R["pooled"]
    L.append(f"| todos | {p['v_med']:.3f} | {p['v_p90']:.3f} | {p['w_med']:.3f} | {p['w_p90']:.3f} | {100*p['w_below_dz']:.1f} % | {100*p['frac_idle']:.1f} % |")
    if R["competition"]:
        q = R["competition"]
        L.append(f"| competicao `{q['label']}` ({q['n_events']} ev) | {q['v_med']:.3f} | {q['v_p90']:.3f} | {q['w_med']:.3f} | {q['w_p90']:.3f} | {100*q['w_below_dz']:.1f} % | {100*q['frac_idle']:.1f} % |")
    f = R["flags"]
    L += ["", f"Flags: chute reto em {f['kick_front_ticks']} ticks, chip em {f['chip_ticks']} ticks, dribbler ligado em {100*f['dribbler_frac']:.1f} % dos ticks; "
          f"|v| max {p['v_max']:.2f} m/s, |w| max {p['w_max']:.2f} rad/s, |v| > 2.9 m/s em {100*p['v_above_2p9']:.1f} %.", "",
          f"## Round trip no harness (janelas re-ancoradas, theta oficial; e_pos mediano em h_ref = {R['h_ref_s']:.2f} s)", "",
          "| robo | N | janelas | twin med | twin p90 | ideal med |", "|---|---|---|---|---|---|"]
    for rid, x in R["replay"].items():
        L.append(f"| {rid} | {x['n']} | {x['windows']} (parado {x['idle']}) | {x['twin_med_href']:.4f} | {x['twin_p90_href']:.4f} | {x['ideal_med_href']:.4f} |")
    L += ["", "Leitura: sessao gerada pelo backend fopdt -> o twin deve reproduzir as poses gravadas ao nivel do mm (residuo = "
          "reamostragem do loader + contatos com bola/robos/paredes); a cinematica ideal fica no gap usual (~0.1 m), como nos logs reais. "
          "A coluna |w|<0.58 compara a fracao de comandos de guinada abaixo do equivalente de corpo da zona morta com a dos logs de competicao."]
    return L


def run(root: Path | None = None, out: Path | None = None, *, session: str = "results/sessao_01",
        label: str = "shoot_to_goal", robots: str | None = None, stride: int | None = None,
        quiet: bool = False, **kw) -> dict:
    ctx = C.make_context(root, out)
    R = compute(ctx, session, label=label, robots=[r for r in robots.split(",")] if robots else None, stride=stride)
    L = render(ctx, R)
    p = ctx.write_text(f"{NAME}_{R['name']}", L)
    pj = ctx.out_path(f"{NAME}_{R['name']}", "json")
    pj.write_text(json.dumps(R, indent=2, default=str), encoding="utf-8")
    R.update(path=p, json=pj)
    if not quiet:
        print("\n".join(L))
        print(f"\nartefato: {p}\njson: {pj}")
    return R


def main(argv=None):
    return C.cli_main(run, __doc__, argv)


if __name__ == "__main__":
    main()
