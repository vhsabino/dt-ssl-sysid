def _jsonable(o: Any) -> Any:
    if isinstance(o, dict):
        return {str(k): _jsonable(v) for k, v in o.items() if not str(k).startswith("_")}
    if isinstance(o, (list, tuple)):
        return [_jsonable(v) for v in o]
    if isinstance(o, (np.floating, np.integer)):
        return o.item()
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, float) and not math.isfinite(o):
        return None
    return o


def run(root: Path | None = None, out: Path | None = None, *, control: str | None = None,
        n_init: int = N_INIT, n_iter: int = N_ITER, seed: int = SEED, max_train_events: int | None = None,
        quiet: bool = False, **kw) -> dict:
    ctx = C.make_context(root, out, seed=seed)
    r = compute(ctx, control=control, n_init=int(n_init), n_iter=int(n_iter), seed=int(seed),
                max_train_events=None if max_train_events is None else int(max_train_events))
    stem = NAME if control is None else f"{NAME}_control-{control}"
    L = render(ctx, r)
    p = ctx.write_text(stem, L)
    pj = ctx.out_path(stem, "json")
    pj.write_text(json.dumps(_jsonable(r), indent=1, ensure_ascii=True), encoding="utf-8")
    pc = ctx.out_path(stem, "csv")
    with open(pc, "w", newline="", encoding="utf-8") as f:
        names = [s["name"] for s in r["space"]]
        w = csv.writer(f)
        w.writerow(["i", *names, "J_m", "cost_s"])
        for h in r["history"]:
            w.writerow([h["i"], *[f"{h['values'][n]:.6g}" for n in names], f"{h['J']:.6f}", f"{h['cost_s']:.1f}"])
    if not quiet:
        print("\n".join(L))
        print(f"\nartefato: {p}\njson: {pj}\ncsv: {pc}")
    r.update(path=p, json=pj, csv=pc)
    return r


def main(argv=None):
    return C.cli_main(run, __doc__, argv)


if __name__ == "__main__":
    main()
