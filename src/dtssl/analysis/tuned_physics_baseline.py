"""Tuned physics baseline (C3 / WP3): MuJoCo route b calibrated on the training events and scored on the
frozen hold-out against the behavioral twin, same windows and same metric as every other number.

Pre-registration: docs/PREREGISTRO_C3_BASELINE_SINTONIZADA_20261014.md (written before any run on real data).
Nothing here is executed until Victor and the advisor decide (backlog item C3, frozen); the code and the
synthetic tests exist so that the run, when authorised, is a single command.

What is tuned (``SPACE``, log-scaled, physically bounded)::

    mu                effective sliding friction of the roller-floor contact (floor plane AND roller geoms
                      set to the same value, so MuJoCo's max-rule gives exactly mu)       [0.4, 1.6]
    impratio          friction-cone impedance ratio of the solver (slip stiffness)          [1, 30]
    kv_wheel          wheel speed-loop gain (N m s/rad), the drive's time constant          [0.02, 0.5]
    wheel_torque_max  torque limit at the wheel (N m), the acceleration limit               [0.3, 3.0]
    gear_ratio        gearbox ratio, i.e. the reflected rotor inertia N^2 J_rotor           [1.5, 8.0]

The identified per-DOF transport delay of the twin is applied to the command stream of the physical
model (``WorldPlant(..., delay="theta")``, the ``mujoco-rollers-delay`` plant of C2a): the delay is a
property of the radio and firmware, not of the contact, and the untuned route b with that delay is the
best physics of C2a (0.0477 m). ``DEFAULTS`` reproduces that plant exactly (floor 0.9 vs roller 1.0 gives
an effective 1.0 by the max-rule; the tuned plant sets both to ``mu``).

Objective (training events only, never the hold-out): the per-window median of ``e_pos`` at ``h_ref``
in the translational bin of the paper's free-run harness (re-anchored windows, stride 15, H_max 90).
Optimiser: Bayesian optimisation, Gaussian process (Matern 5/2 with ARD, scikit-learn) and expected
improvement, after a scrambled Sobol design; the untuned point is always the first evaluation; every
step is seeded, so the run is deterministic. Without scikit-learn the search degrades to the Sobol
design alone and says so in the artefact.

Scored on the hold-out: twin (``fopdt``), untuned route b + delay, tuned route b + delay. Pre-registered
readings T1 (twin vs tuned, the C2b per-event gate in both directions), T2 (gain of the tuning over the
untuned physics), T3 (overfitting: hold-out gain against training gain), V (validity: reproducible
incumbent, parameters off the bounds) and the near-optimal spread of each parameter (what the logs
identify). In-silico control (``control="rollers"``): logs generated by route b at known parameters,
tuned with a small budget; the tuner has to recover a generator of its own model class.

Does NOT touch config/twin_params.json, the promoted theta or any artefact.
"""
