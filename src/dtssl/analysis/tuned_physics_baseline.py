def training_segments(ctx: C.Ctx, labels: Sequence[str] = LABELS, max_events: int | None = None,
                      min_displacement_m: float = C.MIN_DISPLACEMENT_M) -> list[Segment]:
    """Every moving competition event of ``labels`` that is NOT in the frozen hold-out, in dataset order."""
    ho = {(e["label"], e["event"]) for e in ctx.holdout_cfg["events"]}
    out: list[Segment] = []
    for label in labels:
        for ev in C.list_events(ctx.splits_dir, label):
            if (label, ev) in ho:
                continue
            seg = ctx.segment(label, ev)
            if segment_is_moving(seg, min_displacement_m, 0.0):
                out.append(seg)
    if max_events is not None:
        out = out[:int(max_events)]
    return out


def synthetic_segment(name: str, t: np.ndarray, cmd: np.ndarray, pose: np.ndarray, ts: float,
                      label: str = "synthetic") -> Segment:
    """A loader-shaped ``Segment`` from a simulated trajectory (noise-free, world frame, uniform grid)."""
    t = np.asarray(t, float)
    cmd = np.asarray(cmd, float)
    pose = np.asarray(pose, float)
    dt = np.empty_like(t)
    dt[1:] = np.diff(t)
    dt[0] = ts
    vxw, vyw = np.gradient(pose[:, 0], t), np.gradient(pose[:, 1], t)
    vbx, vby, vbw = body_velocity_series(t, pose[:, 0], pose[:, 1], pose[:, 2])
    return Segment(meta=dict(dataset="synthetic", label=label, event=name, ts=ts, team="synthetic", robot_id=0),
                   ts=float(ts), t=t, dt=dt, cmd_vx=cmd[:, 0], cmd_vy=cmd[:, 1], cmd_w=cmd[:, 2],
                   pos_x=pose[:, 0], pos_y=pose[:, 1], theta=pose[:, 2], vel_x_world=vxw, vel_y_world=vyw,
                   velb_x=vbx, velb_y=vby, velb_w=vbw, pose0=tuple(float(v) for v in pose[0]),
                   velb0=(float(vbx[0]), float(vby[0]), float(vbw[0])))


def simulate_segment(plant: Plant, seg: Segment, name: str | None = None) -> Segment:
    """Replay the commands of ``seg`` through ``plant`` from the segment's own pose0 (velocity 0, empty
    delay buffer) and return the simulated trajectory as a new synthetic segment."""
    cmd = np.column_stack([seg.cmd_vx, seg.cmd_vy, seg.cmd_w]).astype(float)
    plant.reset(tuple(seg.pose0), (0.0, 0.0, 0.0))
    plant.prime_delay([])
    pose = np.empty((seg.n, 3))
    pose[0] = seg.pose0
    for k in range(1, seg.n):
        pose[k] = plant.step(cmd[k - 1], seg.ts)
    return synthetic_segment(name or f"synthetic_{seg.meta.get('event')}", seg.t, cmd, pose, seg.ts,
                             label=str(seg.meta.get("label", "synthetic")))


def control_segments(ctx: C.Ctx, factory: Callable[[dict[str, float]], Plant], truth: dict[str, float],
                     labels: Sequence[str] = LABELS, n_train: int = CONTROL_N_TRAIN,
                     n_test: int = CONTROL_N_TEST) -> tuple[list[Segment], list[Segment]]:
    """Synthetic logs of a generator of the model class at ``truth``: the commands of the first training
    events (round robin over ``labels``) replayed through ``factory(truth)``."""
    per_label = {label: [s for s in training_segments(ctx, (label,))] for label in labels}
    picked: list[Segment] = []
    i = 0
    while len(picked) < n_train + n_test and any(per_label.values()):
        label = labels[i % len(labels)]
        if per_label[label]:
            picked.append(per_label[label].pop(0))
        i += 1
    plant = factory(truth)
    try:
        sims = [simulate_segment(plant, s) for s in picked]
    finally:
        close = getattr(plant, "close", None)
        if close is not None:
            close()
    return sims[:n_train], sims[n_train:n_train + n_test]


# =========================================================================
# core computation (pure: testable without the dataset or MuJoCo through ``factory`` and ``space``)
# =========================================================================
def compute_from_segments(ctx: C.Ctx, train: Sequence[Segment], test: Sequence[Segment],
                          factory: Callable[[dict[str, float]], Plant], *, space: Sequence[Param] = SPACE,
                          defaults: dict[str, float] = DEFAULTS, n_init: int = N_INIT, n_iter: int = N_ITER,
                          seed: int = SEED, h_ref: int | None = None) -> dict[str, Any]:
    t0 = time.perf_counter()
    obj = HarnessObjective(ctx, train, factory, space=space, h_ref=h_ref)
    res = bayes_opt(obj, len(space), n_init=n_init, n_iter=n_iter, seed=seed, x0=values_to_unit(defaults, space))
    best_values = unit_to_values(res["best_x"], space)
    J_default_train = float(obj.history[0]["J"])            # the untuned point is the first evaluation
    J_repeat = float(obj.score(best_values)["J"])
    t_tune = time.perf_counter() - t0
    t1 = time.perf_counter()
    tobj = HarnessObjective(ctx, test, factory, space=space, h_ref=h_ref)
    untuned = tobj.score(defaults)
    tuned = tobj.score(best_values)
    t_score = time.perf_counter() - t1
    ev_twin = tuned["per_event_twin"]
    out = dict(space=[dict(name=p.name, lo=p.lo, hi=p.hi, log=p.log) for p in space], defaults=dict(defaults),
               best_values=best_values, best_unit=[float(v) for v in res["best_x"]], best_index=int(res["best_index"]),
               optimizer=dict(kind=res["optimizer"], n_init=res["n_init"], n_iter=res["n_iter"], seed=res["seed"],
                              n_eval=len(obj.history)),
               history=obj.history, J_train=dict(untuned=J_default_train, tuned=float(res["best_y"]),
                                                  twin=float(obj.history[0]["J_twin"])),
               n_train=len(obj.segs), n_test=len(tobj.segs),
               holdout=dict(untuned=untuned, tuned=tuned, h_ref=tobj.h_ref, h_ref_s=float(tobj.h_ref * ctx.ts)),
               t1=verdict_t1(ev_twin, tuned["per_event_model"]),
               t1_untuned=verdict_t1(ev_twin, untuned["per_event_model"]),
               t2=verdict_t2(untuned["J"], tuned["J"]),
               t3=verdict_t3(J_default_train, float(res["best_y"]), untuned["J"], tuned["J"]),
               validity=validity(res, J_repeat, space),
               near_optimal=near_optimal_spread(res["X"], res["y"], space),
               sanity_twin_event_median=float(np.median(ev_twin)),
               cost_s=dict(tuning=t_tune, scoring=t_score))
    return out


def compute(ctx: C.Ctx, *, control: str | None = None, n_init: int = N_INIT, n_iter: int = N_ITER,
            seed: int = SEED, max_train_events: int | None = None,
            factory: Callable[[dict[str, float]], Plant] | None = None) -> dict[str, Any]:
    factory = factory or (lambda values: make_tuned_plant(values, ctx.params))
    t0 = time.perf_counter()
    if control is None:
        train = training_segments(ctx, max_events=max_train_events)
        test, dropped = ctx.holdout()
        budget = (n_init, n_iter)
    else:
        if control not in CONTROLS:
            raise ValueError(f"unknown control {control!r}; known: {', '.join(CONTROLS)}")
        train, test = control_segments(ctx, factory, CONTROL_TRUTH)
        dropped = []
        budget = CONTROL_BUDGET
    load_s = time.perf_counter() - t0
    r = compute_from_segments(ctx, train, test, factory, n_init=budget[0], n_iter=budget[1], seed=seed)
    r.update(control=control, labels=list(LABELS), dropped=dropped, load_s=load_s,
             train_events=[s.meta.get("event") for s in train], test_events=[s.meta.get("event") for s in test])
    if control is not None:
        hu, ht = r["holdout"]["untuned"]["J"], r["holdout"]["tuned"]["J"]
        r["control"] = dict(generator=control, truth=dict(CONTROL_TRUTH), J_untuned=hu, J_tuned=ht,
                            ratio=float(ht / hu) if hu > 0 else float("nan"),
                            passes=bool(hu > 0 and ht <= CONTROL_MAX_RATIO * hu))
    return r


