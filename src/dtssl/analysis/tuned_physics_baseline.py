# harness objective
# =========================================================================
class HarnessObjective:
    """Median ``e_pos`` at ``h_ref`` over the translational windows of ``segs`` for the plant that
    ``factory(values)`` builds (one plant reused across the segments; closed after scoring). The twin
    rollouts are computed once: they fix the window grid and the paired table of the paper's harness."""

    def __init__(self, ctx: C.Ctx, segs: Sequence[Segment], factory: Callable[[dict[str, float]], Plant],
                 space: Sequence[Param] = SPACE, h_ref: int | None = None):
        self.ctx = ctx
        self.segs = list(segs)
        self.factory = factory
        self.space = tuple(space)
        self.H = list(ctx.horizons)
        self.h_ref = int(ctx.mcfg["verdict"]["h_ref"] if h_ref is None else h_ref)
        self.k = self.H.index(self.h_ref)
        self.twin_ros = C.ros(self.segs, lambda: AnalyticFOPDTPlant(ctx.params), horizons=self.H)
        self.history: list[dict[str, Any]] = []

    def score(self, values: dict[str, float]) -> dict[str, Any]:
        t0 = time.perf_counter()
        plant = self.factory(values)
        try:
            ros = C.ros(self.segs, lambda: plant, horizons=self.H)
        finally:
            close = getattr(plant, "close", None)
            if close is not None:
                close()
        T = C.paired_table(self.ctx, self.twin_ros, ros)
        m = C.trans_mask(T)
        ev_t, ev_m, ids = C.per_event_medians(T, self.k, m)
        return dict(J=float(np.median(T.epos_def[m, self.k])), J_twin=float(np.median(T.epos_twin[m, self.k])),
                    rows=[dict(h=int(h), h_s=float(h * T.ts), model=float(np.median(T.epos_def[m, kk])),
                               twin=float(np.median(T.epos_twin[m, kk])),
                               eang_model=float(np.median(T.eang_def[m, kk])),
                               eang_twin=float(np.median(T.eang_twin[m, kk]))) for kk, h in enumerate(self.H)],
                    per_event_model=[float(v) for v in ev_m], per_event_twin=[float(v) for v in ev_t],
                    event_ids=[int(i) for i in ids], events=[self.segs[i].meta.get("event") for i in ids],
                    n_windows=int(T.W), n_trans=int(m.sum()), cost_s=time.perf_counter() - t0)

    def __call__(self, u: Sequence[float]) -> float:
        values = unit_to_values(u, self.space)
        r = self.score(values)
        self.history.append(dict(i=len(self.history), u=[float(x) for x in np.asarray(u, float)],
                                 values=values, J=r["J"], J_twin=r["J_twin"], cost_s=r["cost_s"]))
        return r["J"]


# =========================================================================
# Bayesian optimisation (Gaussian process + expected improvement), deterministic
# =========================================================================
def _fit_gp(X: np.ndarray, y: np.ndarray, seed: int):
    from sklearn.gaussian_process import GaussianProcessRegressor
    from sklearn.gaussian_process.kernels import ConstantKernel, Matern, WhiteKernel

    dim = X.shape[1]
    kernel = (ConstantKernel(1.0, (1e-3, 1e3))
              * Matern(length_scale=np.full(dim, 0.3), length_scale_bounds=(0.05, 5.0), nu=2.5)
              + WhiteKernel(1e-5, (1e-8, 1e-1)))
    gp = GaussianProcessRegressor(kernel=kernel, normalize_y=True, n_restarts_optimizer=2, random_state=seed)
    with warnings.catch_warnings():
        # a deterministic objective drives the noise level to its lower bound and the length scales of
        # irrelevant directions to their upper bound: expected, not a problem of the fit
        warnings.simplefilter("ignore")
        gp.fit(X, y)
    return gp


def _sobol(dim: int, n: int, seed: int) -> np.ndarray:
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")           # balance warning when n is not a power of two
        return qmc.Sobol(d=dim, scramble=True, seed=seed).random(max(int(n), 1))


def expected_improvement(gp, cand: np.ndarray, best: float, y_scale: float = 1.0, xi: float = EI_XI) -> np.ndarray:
    """EI for minimisation at ``cand``: ``best`` is the incumbent objective and ``xi`` the exploration margin
    in units of ``y_scale`` (the standard deviation of the objectives observed so far)."""
    mu, sd = gp.predict(np.asarray(cand, float), return_std=True)
    sd = np.maximum(np.asarray(sd, float), 1e-12)
    imp = best - mu - xi * max(float(y_scale), 1e-12)
    z = imp / sd
    return imp * norm.cdf(z) + sd * norm.pdf(z)


def bayes_opt(f: Callable[[np.ndarray], float], dim: int, *, n_init: int = N_INIT, n_iter: int = N_ITER,
              seed: int = SEED, x0: np.ndarray | None = None, n_candidates: int = N_CANDIDATES,
              n_refine: int = N_REFINE) -> dict[str, Any]:
    """Minimise ``f`` on the unit cube: ``n_init`` scrambled Sobol points (``x0`` replaces the first) then
    ``n_iter`` EI steps. Deterministic for a given seed. Falls back to the design alone without scikit-learn."""
    design = _sobol(dim, n_init, seed)
    if x0 is not None:
        design[0] = np.clip(np.asarray(x0, float).reshape(dim), 0.0, 1.0)
    X = [np.asarray(x, float) for x in design]
    y = [float(f(x)) for x in X]
    optimizer = "gp-ei"
    try:
        import sklearn  # noqa: F401
    except ImportError:  # pragma: no cover - the PC has scikit-learn
        optimizer = "sobol-only"
        n_iter = 0
    bounds = [(0.0, 1.0)] * dim
    for it in range(int(n_iter)):
        Xa, ya = np.vstack(X), np.asarray(y, float)
        gp = _fit_gp(Xa, ya, seed + it)
        best, y_scale = float(ya.min()), float(ya.std()) if ya.size > 1 else 1.0
        cand = _sobol(dim, n_candidates, seed + 1000 + it)
        ei = expected_improvement(gp, cand, best, y_scale)
        top = cand[np.argsort(-ei)[:max(int(n_refine), 1)]]
        best_x, best_ei = top[0], float(ei.max())

        def neg_ei(z, gp=gp, best=best, y_scale=y_scale):
            return -float(expected_improvement(gp, z[None, :], best, y_scale)[0])

        for c in top:
            res = minimize(neg_ei, c, bounds=bounds, method="L-BFGS-B")
            if -float(res.fun) > best_ei:
                best_ei, best_x = -float(res.fun), np.clip(res.x, 0.0, 1.0)
        X.append(np.asarray(best_x, float))
        y.append(float(f(best_x)))
    ya = np.asarray(y, float)
    i = int(np.argmin(ya))
    return dict(X=np.vstack(X), y=ya, best_x=np.vstack(X)[i], best_y=float(ya[i]), best_index=i,
                n_init=int(n_init), n_iter=int(n_iter), optimizer=optimizer, seed=int(seed))


def near_optimal_spread(X: np.ndarray, y: np.ndarray, space: Sequence[Param] = SPACE,
                        tol: float = NEAR_OPT_TOL) -> dict[str, Any]:
    """Range of every parameter over the evaluated points within ``tol`` of the best objective (unit scale
    and physical values): a wide range is a parameter the training logs do not pin down."""
    y = np.asarray(y, float)
    sel = y <= y.min() * (1.0 + tol)
    Xs = np.asarray(X, float)[sel]
    out = {}
    for j, p in enumerate(space):
        lo, hi = float(Xs[:, j].min()), float(Xs[:, j].max())
        out[p.name] = dict(unit_min=lo, unit_max=hi, span=hi - lo, value_min=p.to_value(lo),
                           value_max=p.to_value(hi), identified=bool(hi - lo < 0.5))
    return dict(n_points=int(sel.sum()), tol=float(tol), params=out)


# =========================================================================
# pre-registered verdicts
# =========================================================================
def _gate(a: np.ndarray, b: np.ndarray) -> dict[str, Any]:
    """``a`` beats ``b`` per event under the C2b gate (wins, one-sided Wilcoxon a < b, rank-biserial)."""
    wins = int(np.sum(a < b))
    p = wilcoxon_less(a, b)
    rb = rank_biserial(b, a)
    return dict(wins=wins, n=int(a.size), p=float(p), rb=float(rb),
                passes=bool(wins >= GATE["wins"] and p < GATE["p"] and rb >= GATE["rb"]))


def verdict_t1(ev_twin: Sequence[float], ev_tuned: Sequence[float]) -> dict[str, Any]:
    """T1: per-event medians at h_ref on the hold-out; the gate in both directions; three readings."""
    a, b = np.asarray(ev_twin, float), np.asarray(ev_tuned, float)
    twin = _gate(a, b)
    tuned = _gate(b, a)
    reading = "twin" if twin["passes"] else "tuned" if tuned["passes"] else "tie"
    return dict(twin_beats_tuned=twin, tuned_beats_twin=tuned, reading=reading,
                median_twin=float(np.median(a)), median_tuned=float(np.median(b)))


def verdict_t2(J_untuned: float, J_tuned: float) -> dict[str, Any]:
    """T2: relative gain of the tuned over the untuned physics (per-window median at h_ref, hold-out)."""
    gain = 1.0 - float(J_tuned) / float(J_untuned) if J_untuned > 0 else 0.0
    return dict(J_untuned=float(J_untuned), J_tuned=float(J_tuned), gain=float(gain),
                passes=bool(gain >= T2_MIN_GAIN))


def verdict_t3(train_untuned: float, train_tuned: float, hold_untuned: float, hold_tuned: float) -> dict[str, Any]:
    """T3: the hold-out keeps at least ``T3_MIN_FRACTION`` of the training gain (otherwise overfitting)."""
    g_train = 1.0 - train_tuned / train_untuned if train_untuned > 0 else 0.0
    g_hold = 1.0 - hold_tuned / hold_untuned if hold_untuned > 0 else 0.0
    ratio = g_hold / g_train if g_train > 1e-9 else float("nan")
    overfit = bool(g_train > 1e-9 and (not math.isfinite(ratio) or ratio < T3_MIN_FRACTION))
    return dict(gain_train=float(g_train), gain_holdout=float(g_hold), ratio=float(ratio), overfitting=overfit,
                passes=bool(not overfit))


def validity(res: dict[str, Any], J_repeat: float, space: Sequence[Param] = SPACE) -> dict[str, Any]:
    """V: the incumbent re-evaluates to the same objective and sits inside the bounds."""
    bx = np.asarray(res["best_x"], float)
    at_bound = [p.name for p, u in zip(space, bx, strict=True) if u <= BOUND_TOL or u >= 1.0 - BOUND_TOL]
    repro = abs(float(J_repeat) - float(res["best_y"])) <= REPRO_TOL_M
    return dict(reproducible=bool(repro), J_best=float(res["best_y"]), J_repeat=float(J_repeat),
                at_bound=at_bound, passes=bool(repro and len(at_bound) <= BOUND_MAX))


