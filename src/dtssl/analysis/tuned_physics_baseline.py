@dataclass(frozen=True)
class Param:
    """One tuned quantity: ``[lo, hi]`` mapped to the unit cube (log-uniform when ``log``)."""
    name: str
    lo: float
    hi: float
    log: bool = True

    def to_value(self, u: float) -> float:
        u = min(max(float(u), 0.0), 1.0)
        if self.log:
            return float(math.exp(math.log(self.lo) + u * (math.log(self.hi) - math.log(self.lo))))
        return float(self.lo + u * (self.hi - self.lo))

    def to_unit(self, v: float) -> float:
        v = float(v)
        if self.log:
            u = (math.log(v) - math.log(self.lo)) / (math.log(self.hi) - math.log(self.lo))
        else:
            u = (v - self.lo) / (self.hi - self.lo)
        return float(min(max(u, 0.0), 1.0))


SPACE: tuple[Param, ...] = (
    Param("mu", 0.4, 1.6),
    Param("impratio", 1.0, 30.0),
    Param("kv_wheel", 0.02, 0.5),
    Param("wheel_torque_max", 0.3, 3.0),
    Param("gear_ratio", 1.5, 8.0),
)
#: the untuned route b (RouteBOptions / SolverOptions defaults; floor 0.9 vs roller 1.0 -> effective mu = 1.0)
DEFAULTS: dict[str, float] = dict(mu=1.0, impratio=10.0, kv_wheel=0.1, wheel_torque_max=1.5, gear_ratio=4.0)


def unit_to_values(u: Sequence[float], space: Sequence[Param] = SPACE) -> dict[str, float]:
    u = np.asarray(u, dtype=float).reshape(-1)
    if u.size != len(space):
        raise ValueError(f"expected {len(space)} coordinates, got {u.size}")
    return {p.name: p.to_value(x) for p, x in zip(space, u, strict=True)}


def values_to_unit(values: dict[str, float], space: Sequence[Param] = SPACE) -> np.ndarray:
    return np.array([p.to_unit(values[p.name]) for p in space], dtype=float)


def world_opts(values: dict[str, float]) -> dict[str, Any]:
    """``MuJoCoWorld`` options of a parameter set: route b drive and contact, solver impedance, floor friction."""
    from dtssl.physics.mjcf import RouteBOptions, SolverOptions

    mu = float(values["mu"])
    rb = replace(RouteBOptions(), roller_friction=mu, kv_wheel=float(values["kv_wheel"]),
                 wheel_torque_max=float(values["wheel_torque_max"]), gear_ratio=float(values["gear_ratio"]))
    return dict(route_b=rb, solver=replace(SolverOptions(), impratio=float(values["impratio"])), floor_friction=mu)


def make_tuned_plant(values: dict[str, float], params: dict[str, DofParam] | None = None,
                     delay: str | None = "theta") -> Plant:
    """Route b (``mujoco-rollers``) with ``values`` and the identified per-DOF delay, as a harness plant."""
    from dtssl.sim.world_plant import WorldPlant

    return WorldPlant("mujoco-rollers", params=params, delay=delay, world_opts=world_opts(values))


