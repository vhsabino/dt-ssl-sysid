def _p(p: float) -> str:
    """p-value as LaTeX (``9.8\\times10^{-4}``)."""
    if p >= 0.01:
        return f"{p:.3f}".rstrip("0").rstrip(".") if p < 0.1 else f"{p:.2f}"
    mant, exp = f"{p:.1e}".split("e")
    return f"{mant}\\times10^{{{int(exp)}}}"


def _f(v: float | None, nd: int = 3) -> str:
    return "--" if v is None else f"{v:.{nd}f}"


def _wrap(name: str, caption: str, label: str, colspec: str, head: list[str], body: list[str],
          sources: list[str], note: str | None = None, star: bool = False) -> str:
    env = "table*" if star else "table"
    lines = ["% " + "=" * 78, f"% {name}: generated by `dtssl analysis run journal_tables` (dtssl.analysis.journal_tables).",
             "% Do not edit by hand: re-run the generator. Sources:"]
    lines += [f"%   {s}" for s in sources]
    lines += ["% " + "=" * 78, "% Needs \\usepackage{booktabs,adjustbox}.",
              f"\\begin{{{env}}}[t]", "\\centering", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
              "\\small", "\\begin{adjustbox}{max width=\\textwidth}", f"\\begin{{tabular}}{{{colspec}}}", "\\toprule"]
    lines += head + ["\\midrule"] + body + ["\\bottomrule", "\\end{tabular}", "\\end{adjustbox}"]
    if note:
        lines += ["", "\\vspace{2pt}", f"\\parbox{{\\linewidth}}{{\\footnotesize {note}}}"]
    lines += [f"\\end{{{env}}}", ""]
    return "\n".join(lines)


