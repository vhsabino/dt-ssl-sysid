def table_insilico_yaw(root: Path | None = None) -> str:
    y = J.yaw_insilico(root)
    gens = (("linear twin", "linear FOPDT twin"), ("route b", "MuJoCo rollers"), ("route b + delay", "MuJoCo rollers + delay"))
    cells = (("none", "off"), ("vision", "on"))
    regimes = (("R1", "competition commands"), ("R1-wonly", "same, translation zeroed"),
               ("R2-rotate", "dedicated rotation"), ("R2-square", "square maneuvers"),
               ("R3*", "designed excitation"))

    def cell(g, regime, c):
        key = regime
        if regime == "R3*":
            key = "R3" if g == "linear twin" else "R3-mild"
        v = y[g].get((key, *c))
        if v is None:
            return "--"
        return f"{v['med']:.3f} [{v['p25']:.3f}, {v['p75']:.3f}]"

    head = ["& " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{lab}}}" for _, lab in gens) + " \\\\",
            " ".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(3)),
            "regime & " + " & ".join(["idealized", "noise + dead zone"] * 3) + " \\\\"]
    body = []
    for key, lab in regimes:
        body.append(f"{lab} & " + " & ".join(cell(g, key, c) for g, _ in gens for c in cells) + " \\\\")
    design = J.load_json("c1", root)["design"]
    sig_mm, sig_rad = design["noises"]["vision"]
    n_lin = y["linear twin"][("R1", "none", "off")]["n_rep"]
    n_phys = y["route b + delay"][("R1", "none", "off")]["n_rep"]
    k_cl = J.r3(root)["closed_loop"]["K"]
    k_ol = float(C.make_context(root).params["w"].K)
    note = (f"Median [25th, 75th percentile] over replicates ({n_lin} for the linear twin, {n_phys} for MuJoCo). "
            "Idealized: no measurement noise, dead zone off; noise + dead zone: vision noise of "
            f"{sig_mm:g} mm and {sig_rad:g} rad with the firmware per-wheel dead zone. Designed excitation: R3 for the "
            "linear twin, the milder R3-mild inside the traction envelope of the rollers model for MuJoCo. Real "
            f"robot: {k_cl:.3f} from closed-loop logs, {k_ol:.3f} from the dedicated collection.")
    return _wrap("tab_journal_insilico_yaw", "Yaw gain re-identified from synthetic logs generated with a known plant, "
                 "by excitation regime and generator.", "tab:insilico-yaw", "lcccccc", head, body,
                 [f"results/{J.ARTEFACTS[k]}" for k in ("c1", "c1b_nodelay", "c1b_delay", "r3")]
                 + ["config/twin_params.json (K_w = 1.0016)"], note=note, star=True)


