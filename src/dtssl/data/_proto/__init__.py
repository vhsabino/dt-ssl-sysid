"""Vendored protobuf bindings for the ssl-unification log format (``RCLog.Log``).

The ``.proto`` files in this directory are verbatim copies of
``<ssl-unification>/libs/protobufs/include/protobufs/pb/proto``: ``rc_log.proto`` (the record type
written by the ssl-unification Logger) and the game-controller referee message it embeds
(``ssl_gc_referee_message`` -> ``ssl_gc_game_event`` -> ``ssl_gc_geometry``). The ssl-vision wrapper
and ``ssl_gc_common`` that ``rc_log.proto`` also imports are **shared with** :mod:`dtssl.bridge.proto`
(imported from there, never duplicated: a ``.proto`` file may be registered only once in the
process-wide descriptor pool). The ``*_pb2.py`` modules are generated by
:mod:`dtssl.data._proto.build_proto` (grpcio-tools) and versioned, so users only need the ``protobuf``
runtime. They replace the betterproto-generated ``python/proto/generated/{RCLog,RoboCupSSL}.py`` of
the legacy notebooks (betterproto is no longer required).

This module is the ONLY place that knows which generator produced the classes. Everything else
(:mod:`dtssl.data.extract`, tests) goes through the small accessor layer below, whose contract is:

* :func:`decode_log` / :func:`encode_log` / :func:`new_log` -- bytes <-> ``Log`` message;
* sub-messages are returned as objects exposing the *proto field names* as attributes
  (``publish_timestamp``, ``ball.position.x``, ``allies[i].id`` ...);
* :func:`raw_frames`, :func:`processed_frame`, :func:`referee`, :func:`raw_referee`,
  :func:`telemetries`, :func:`robot_commands` hide presence semantics (``HasField``) and the one
  camel-case field of the schema (``Log.rawReferee``);
* :func:`has_field` for presence checks on any message.

Ownership of the ``RoboCupSSL`` messages: vision + ``ssl_gc_common`` -> ``dtssl.bridge.proto``;
referee/game events -> here. If the bridge ever needs the referee message, import it from this
package instead of generating a second copy.
"""
from __future__ import annotations

from collections.abc import Sequence
from typing import Any

BACKEND = "protobuf"

_pb: Any = None


class ProtoUnavailableError(ImportError):
    """Raised when the protobuf runtime cannot be imported."""


class LogDecodeError(ValueError):
    """Raised by :func:`decode_log` when a payload is not a parseable ``RCLog.Log``."""


def _load():
    """Import the generated modules lazily (clear error if the runtime is missing)."""
    global _pb
    if _pb is None:
        try:
            from . import rc_log_pb2 as pb
        except ImportError as e:  # pragma: no cover - environment dependent
            raise ProtoUnavailableError(
                f"The protobuf runtime is required to decode ssl-unification logs "
                f"(pip install protobuf). Original error: {e}"
            ) from e
        _pb = pb
    return _pb


# --------------------------------------------------------------------------- classes
def log_class():
    """The ``RCLog.Log`` message class (top-level record of the log)."""
    return _load().Log


def new_log():
    """A fresh, empty ``RCLog.Log`` message (use it to build synthetic logs)."""
    return _load().Log()


def message_module():
    """The generated ``rc_log_pb2`` module (``Frame``, ``Telemetry``, ``RobotsCommand`` ...)."""
    return _load()


# --------------------------------------------------------------------------- codec
def decode_log(payload: bytes):
    """Parse one recordio payload into a ``RCLog.Log``.

    Parsing is *permissive*: missing ``required`` fields and unknown enum values (newer
    ssl-vision / game-controller versions) do not raise; only malformed wire data does.
    """
    msg = _load().Log()
    try:
        msg.ParseFromString(bytes(payload))
    except Exception as e:  # google.protobuf.message.DecodeError (runtime-specific class)
        raise LogDecodeError(str(e)) from e
    return msg


def encode_log(log) -> bytes:
    """Serialize a ``Log`` (partial serialization: required fields may be unset)."""
    return log.SerializePartialToString()


# --------------------------------------------------------------------------- accessors
def has_field(msg, name: str) -> bool:
    """Presence of a singular (message or scalar) field, generator-agnostic."""
    return bool(msg.HasField(name))


def raw_frames(log) -> Sequence:
    """``Log.raw_frame`` entries (``publish_timestamp``, ``packet`` = SSL_WrapperPacket)."""
    return log.raw_frame


def processed_frame(log):
    """``Log.processed_frame`` (``Frame``) or ``None`` when absent."""
    return log.processed_frame if log.HasField("processed_frame") else None


def referee(log):
    """``Log.referee`` (``publish_timestamp``, ``game_state_name``) or ``None``."""
    return log.referee if log.HasField("referee") else None


def raw_referee(log):
    """``Log.rawReferee`` (``publish_timestamp``, ``packet`` = RoboCupSSL.Referee) or ``None``."""
    return log.rawReferee if log.HasField("rawReferee") else None


def telemetries(log) -> Sequence:
    """``Log.telemetry.telemetries`` entries (empty when the telemetry block is absent)."""
    return log.telemetry.telemetries if log.HasField("telemetry") else ()


def robot_commands(log) -> Sequence:
    """``Log.robots_command.navigation`` entries (empty when absent)."""
    return log.robots_command.navigation if log.HasField("robots_command") else ()


def to_dict(msg) -> dict:
    """Debug helper: message -> plain dict with proto field names (int64 as int)."""
    from google.protobuf.json_format import MessageToDict

    return MessageToDict(msg, preserving_proto_field_name=True)


__all__ = [
    "BACKEND", "ProtoUnavailableError", "LogDecodeError",
    "log_class", "new_log", "message_module", "decode_log", "encode_log",
    "has_field", "raw_frames", "processed_frame", "referee", "raw_referee",
    "telemetries", "robot_commands", "to_dict",
]
