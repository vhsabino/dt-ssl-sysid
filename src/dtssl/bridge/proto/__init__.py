"""ssl-vision / ssl-simulation-protocol messages (generated ``*_pb2`` modules) + the RobôCIn radio protocol.

The ``.proto`` sources are verbatim copies from ssl-unification
(``libs/protobufs/include/protobufs/pb/proto``); the ``*_pb2.py`` files are generated by
``build_proto.py`` and versioned, so no ``protoc`` is needed at runtime. The most used
message classes are re-exported here::

    from dtssl.bridge.proto import SSL_WrapperPacket, RobotControl, RobotControlResponse
    from dtssl.bridge.proto import RCFeedback          # real-robot telemetry (rc_communication.proto)

``rc_communication.proto`` (package ``RCCommunication``) is what the real robots speak over the radio
(``CommunicationWifi``: commands to multicast 224.0.1.99:19901, ``Feedback`` telemetry back on 19903):
body velocities, per-motor commanded/measured speeds, PWM, error and current, capacitor and battery charge,
ball sensor. ``dtssl.bridge.telemetry`` reads it.

Units on the wire (see docs/SPEC_DTSSL.md §3/§4.4): vision in **mm** and rad, simulation
control/teleport in **m**, m/s and rad, robot control in m/s and rad/s (body frame).
"""
