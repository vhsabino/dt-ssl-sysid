function out = cad_lod(varargin)
%CAD_LOD  Exterior-only LOD of the CAD meshes for the GUI 3D views (from the tools/inventor_export_cad.m OBJ files).
%   out = cad_lod()                          % the four targets, src/dtssl/physics/assets
%   out = cad_lod('Targets', {'chassis'})    % one target
%
%   For each target the full-resolution ssl_<tag>.obj (one 'g' group per CAD part, 'usemtl' per colour, one
%   '# part' header line per part) is read and rendered flat-coloured (one colour per part, no lighting,
%   orthographic) from a set of view directions in an invisible figure, which gives the pixels every part owns
%   when seen from outside. Parts nobody sees are left out of the LOD; the others are decimated with
%   reducepatch, the face budget being shared in proportion to the pixels each part shows (plus a floor of
%   24 faces per part), and written to ssl_<tag>_lod.obj with the same header conventions (the dropped parts
%   are listed in one '# interior' line, the '# part' lines of the kept parts stay in group order, as
%   tools/register_cad_meshes.py expects).
%
%   Why: the exporter used to decimate every part by the same ratio. reducepatch keeps the vertices on the
%   surface, so the chords of the big curved cover and of the plate under it sank by a millimetre through each
%   other and through the parts beneath; the light plate and the aluminium parts came out as white patches on
%   the black robots of the field view. Sharing the budget by visible area keeps the cover, the plate and the
%   shell close to full resolution and spends few faces on what is barely seen.
%
%   Options: 'OutDir' (assets folder), 'Targets', 'FaceTargets' (struct, same budgets as the exporter:
%   chassis_lod 12000, wheel_lod 1200, kicker_lod 1500, dribbler_lod 3500), 'Elevations' (deg, default
%   [90 60 30 10 -30]: the field view looks from above, the Robot tab also from below), 'Azimuths' (deg, default
%   0:30:330), 'Pixels' (render size, default 900), 'MinPixels' (a part is visible when it owns at least this many
%   pixels in some view, default 6). At most 256 parts per mesh (16 x 16 colour codes).
%
%   Run from the repo root (then re-register the meshes):
%       addpath tools; cad_lod();
%       python tools/register_cad_meshes.py

ip = inputParser;
ip.addParameter('OutDir', fullfile(fileparts(fileparts(mfilename('fullpath'))), 'src', 'dtssl', 'physics', 'assets'), @ischar);
ip.addParameter('Targets', {'chassis', 'wheel', 'kicker', 'dribbler'}, @iscell);
ip.addParameter('FaceTargets', struct('chassis_lod', 12000, 'wheel_lod', 1200, 'kicker_lod', 1500, 'dribbler_lod', 3500), @isstruct);
ip.addParameter('Elevations', [90 60 30 10 -30], @isnumeric);
ip.addParameter('Azimuths', 0:30:330, @isnumeric);
ip.addParameter('Pixels', 900, @isnumeric);
ip.addParameter('MinPixels', 6, @isnumeric);
ip.parse(varargin{:});
o = ip.Results;
stamp = char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm'));
out = struct('tag', {}, 'file', {}, 'file_lod', {}, 'n_parts', {}, 'n_visible', {}, 'faces', {}, 'faces_lod', {}, 'interior', {});
for ti = 1:numel(o.Targets)
    tag = o.Targets{ti};
    t0 = tic;
    fn = fullfile(o.OutDir, sprintf('ssl_%s.obj', tag));
    [hdr, mtllib, sel] = read_exporter_obj(fn);
    area = visible_area(sel, o.Elevations, o.Azimuths, o.Pixels);
    vis = area >= o.MinPixels;
    kept = sel(vis);
    nfull = sum(arrayfun(@(l) size(l.F, 1), sel));
    lod = decimate_parts(kept, o.FaceTargets.([tag '_lod']), area(vis));
    nl = sum(arrayfun(@(l) size(l.F, 1), lod));
    interior = {sel(~vis).path};
    isPart = startsWith(hdr, 'part ');
    firstPart = find(isPart, 1);
    if isempty(firstPart), firstPart = numel(hdr) + 1; end
    partLines = reshape(hdr(isPart), 1, []);
    if numel(partLines) ~= numel(sel), error('cad_lod:header', '%s: %d part lines for %d groups', fn, numel(partLines), numel(sel)); end
    note = sprintf('%d of %d parts seen from outside, %d -> %d faces (LOD for the GUI 3D views: tools/cad_lod.m, reducepatch per part of ssl_%s.obj)', ...
                   numel(kept), numel(sel), nfull, nl, tag);
    hdrLod = [{sprintf('generated by tools/cad_lod.m on %s from ssl_%s.obj; do not edit (regenerate: addpath tools; cad_lod)', stamp, tag)}, ...
              hdr(2:3), {note}, hdr(5:firstPart - 1), partLines(reshape(vis, 1, [])), ...
              {sprintf('interior (%d parts not drawn in the LOD): %s', numel(interior), strjoin(interior, ' | '))}];
    fnl = fullfile(o.OutDir, sprintf('ssl_%s_lod.obj', tag));
    write_obj(fnl, lod, hdrLod, mtllib);
    out(end+1) = struct('tag', tag, 'file', fn, 'file_lod', fnl, 'n_parts', numel(sel), 'n_visible', numel(kept), ...
                        'faces', nfull, 'faces_lod', nl, 'interior', {interior}); %#ok<AGROW>
    fprintf('%s: %d of %d parts visible, %d -> %d faces -> %s (%.0f s)\n', tag, numel(kept), numel(sel), nfull, nl, fnl, toc(t0));
end
end


function [hdr, mtllib, sel] = read_exporter_obj(fn)
%READ_EXPORTER_OBJ  Header lines (without '# '), mtllib and one struct per 'g' group (path, mtl, V local, F local 1-based).
lines = splitlines(fileread(fn));
lines = lines(~cellfun(@isempty, lines));
isH = startsWith(lines, '# ');
hdr = reshape(cellfun(@(s) s(3:end), lines(isH), 'UniformOutput', false), 1, []);
m = lines(startsWith(lines, 'mtllib '));
if isempty(m), error('cad_lod:obj', '%s: no mtllib line', fn); end
mtllib = strtrim(m{1}(8:end));
isV = startsWith(lines, 'v ');
V = reshape(sscanf(strjoin(lines(isV), ' '), ' v %f %f %f'), 3, []).';
isF = startsWith(lines, 'f ');
F = reshape(sscanf(strjoin(lines(isF), ' '), ' f %d %d %d'), 3, []).';
if size(V, 1) ~= nnz(isV) || size(F, 1) ~= nnz(isF), error('cad_lod:obj', '%s: could not parse every v/f line', fn); end
isG = startsWith(lines, 'g ');
isM = startsWith(lines, 'usemtl ');
gIdx = cumsum(isG);
gOfFace = gIdx(isF);
gNames = cellfun(@(s) strtrim(s(3:end)), lines(isG), 'UniformOutput', false);
mNames = cellfun(@(s) strtrim(s(8:end)), lines(isM), 'UniformOutput', false);
mOfLine = cumsum(isM);
mOfGroup = mOfLine(isG);                        % the exporter writes 'usemtl' right after each 'g'
gLine = find(isG);
for k = 1:numel(gLine)                            % usemtl follows its g line
    nxt = gLine(k) + 1;
    if nxt <= numel(lines) && isM(nxt), mOfGroup(k) = mOfLine(nxt); end
end
sel = struct('path', {}, 'mtl', {}, 'V', {}, 'F', {});
for k = 1:numel(gNames)
    Fk = F(gOfFace == k, :);
    if isempty(Fk), continue; end
    [ids, ~, loc] = unique(Fk(:));
    sel(end+1) = struct('path', gNames{k}, 'mtl', mNames{max(mOfGroup(k), 1)}, 'V', V(ids, :), ...
                        'F', reshape(loc, size(Fk))); %#ok<AGROW>
end
end


function area = visible_area(sel, els, azs, px)
%VISIBLE_AREA  Pixels each part owns in the orthographic flat-colour render where it shows most (one colour per part).
nP = numel(sel);
if nP > 256, error('cad_lod:parts', 'more than 256 parts (%d): widen the colour code', nP); end
V = vertcat(sel.V);
nF = sum(arrayfun(@(l) size(l.F, 1), sel));
F = zeros(nF, 3); C = zeros(nF, 3);
off = 0; fo = 0;
for k = 1:nP
    nk = size(sel(k).F, 1);
    F(fo + 1:fo + nk, :) = sel(k).F + off;
    % index code: 16 levels in R and 16 in G, mid-step (8 + 16 i), B = 0; a pixel blended with a neighbour or the
    % white background misses the grid and is ignored (print anti-aliases the edges whatever GraphicsSmoothing says)
    C(fo + 1:fo + nk, :) = repmat([8 + 16 * mod(k - 1, 16), 8 + 16 * floor((k - 1) / 16), 0] / 255, nk, 1);
    off = off + size(sel(k).V, 1); fo = fo + nk;
end
fig = figure('Visible', 'off', 'Color', [1 1 1], 'Units', 'pixels', 'Position', [100 100 px px], ...
             'GraphicsSmoothing', 'off', 'Renderer', 'opengl', 'InvertHardcopy', 'off');
cleaner = onCleanup(@() close(fig)); %#ok<NASGU>
ax = axes('Parent', fig, 'Units', 'normalized', 'Position', [0 0 1 1], 'Visible', 'off');
patch('Parent', ax, 'Faces', F, 'Vertices', V, 'FaceVertexCData', C, 'FaceColor', 'flat', 'EdgeColor', 'none', ...
      'FaceLighting', 'none');
c = (min(V) + max(V)) / 2; r = max(max(V) - min(V)) / 2 * 1.05;
axis(ax, 'equal', 'vis3d', 'off');
xlim(ax, c(1) + [-r r]); ylim(ax, c(2) + [-r r]); zlim(ax, c(3) + [-r r]);
camproj(ax, 'orthographic');
count = zeros(nP, 1);
for el = els(:).'
    azList = azs(:).';
    if abs(el) >= 90, azList = azList(1); end
    for az = azList
        view(ax, az, el);
        drawnow;
        img = print(fig, '-RGBImage', '-r0');
        R = double(img(:, :, 1)); G = double(img(:, :, 2)); B = double(img(:, :, 3));
        m = B == 0 & mod(R, 16) == 8 & mod(G, 16) == 8;
        k = 1 + (R(m) - 8) / 16 + 16 * ((G(m) - 8) / 16);
        k = k(k >= 1 & k <= nP);
        if isempty(k), continue; end
        count = max(count, accumarray(k, 1, [nP 1]));
    end
end
area = count;
end


function sel = decimate_parts(sel, budget, area)
%DECIMATE_PARTS  reducepatch part by part to about `budget` faces in total, each part getting a floor of 24 faces
%   plus a share of the rest proportional to `area` (its visible pixels); colours and groups survive.
n = arrayfun(@(l) size(l.F, 1), sel);
total = sum(n);
if budget <= 0 || total <= budget, return; end
area = area(:).';
target = min(n, 24);                                   % floor
for pass = 1:4                                         % share the rest by visible area; what a part cannot use
    open = target < n;                                 % (it is already at full resolution) goes round again
    rest = budget - sum(target);
    if rest <= 0 || ~any(open) || sum(area(open)) == 0, break; end
    target(open) = min(n(open), target(open) + round(rest * area(open) / sum(area(open))));
end
for k = 1:numel(sel)
    if target(k) >= n(k), continue; end
    [F, V] = reducepatch(sel(k).F, sel(k).V, target(k));
    sel(k).F = F; sel(k).V = V;
end
end


function write_obj(fn, sel, header, mtllib)
%WRITE_OBJ  Triangles-only OBJ with '# ' header lines, one 'g' group per part and 'usemtl' per colour (LF endings).
fid = fopen(fn, 'w');
cleaner = onCleanup(@() fclose(fid)); %#ok<NASGU>
for k = 1:numel(header), fprintf(fid, '# %s\n', header{k}); end
fprintf(fid, 'mtllib %s\n', mtllib);
off = 0;
for k = 1:numel(sel), fprintf(fid, 'v %.6f %.6f %.6f\n', sel(k).V.'); end
for k = 1:numel(sel)
    fprintf(fid, 'g %s\nusemtl %s\n', regexprep(sel(k).path, '\s+', '_'), sel(k).mtl);
    fprintf(fid, 'f %d %d %d\n', (sel(k).F + off).');
    off = off + size(sel(k).V, 1);
end
end
